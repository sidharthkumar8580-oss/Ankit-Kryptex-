AGNES_BASE_URL = os.getenv("AGNES_BASE_URL", "https://apihub.agnes-ai.com").rstrip("/")
RETRYABLE = {401, 402, 403, 408, 429, 500, 502, 503, 504}
HF_TOKEN = os.getenv("HF_TOKEN") or os.getenv("HUGGINGFACEHUB_API_TOKEN") or os.getenv("HUGGING_FACE_HUB_TOKEN")
# Format: owner/space|/api_name,owner2/space2|/api_name
# The default candidate exposes a single prompt-to-video function named infer.
HF_VIDEO_SPACES = os.getenv("HF_VIDEO_SPACES", "K00B404/Wan2.1|/infer")
HF_VIDEO_TASKS = {}
HF_VIDEO_DIR = Path(tempfile.gettempdir()) / "ankit_kryptex_hf_videos"
HF_VIDEO_DIR.mkdir(parents=True, exist_ok=True)

def parse_hf_spaces():
    spaces = []
    for item in HF_VIDEO_SPACES.split(","):
        item = item.strip()
        if not item:
            continue
        if "|" in item:
            space_id, api_name = item.split("|", 1)
        else:
            space_id, api_name = item, ""
        spaces.append((space_id.strip(), api_name.strip() or None))
    return spaces

def find_video_output(value):
    """Find a Gradio video/file output in common Gradio return shapes."""
    if isinstance(value, str):
        if value.startswith(("https://", "http://")):
            return value
        if os.path.isfile(value):
            return value
    if isinstance(value, dict):
        for key in ("url", "video", "path", "name"):
            found = find_video_output(value.get(key))
            if found:
                return found
        for item in value.values():
            found = find_video_output(item)
            if found:
                return found
    if isinstance(value, (list, tuple)):
        for item in value:
            found = find_video_output(item)
            if found:
                return found
    return None

def call_hf_space(space_id, api_name, prompt, token):
    from gradio_client import Client
    client = Client(space_id, token=token or None, verbose=False)
    if api_name:
        return client.predict(prompt, api_name=api_name)
    # Only use the implicit endpoint when the Space exposes a single endpoint.
    return client.predict(prompt)

async def run_hf_video_task(task_id, prompt):
    errors = []
    for space_id, api_name in parse_hf_spaces():
        try:
            HF_VIDEO_TASKS[task_id].update({"status": "processing", "detail": f"Connecting to {space_id}..."})
            result = await asyncio.wait_for(
                run_in_threadpool(call_hf_space, space_id, api_name, prompt, HF_TOKEN),
                timeout=240
            )
            output = find_video_output(result)
            if not output:
                raise RuntimeError(f"{space_id} returned no recognizable video file.")
            if output.startswith(("https://", "http://")):
                video_url = output
            else:
                source = Path(output)
                if not source.is_file():
                    raise RuntimeError(f"{space_id} returned a missing local video file.")
                destination = HF_VIDEO_DIR / f"{task_id}{source.suffix or '.mp4'}"
                destination.write_bytes(source.read_bytes())
                video_url = f"/api/media/hf-file/{task_id}"
            HF_VIDEO_TASKS[task_id].update({
                "status": "completed", "url": video_url, "model": f"HF:{space_id}",
                "progress": 100, "detail": f"Video generated by {space_id}."
            })
            return
        except Exception as exc:
            errors.append(f"{space_id}: {type(exc).__name__}: {str(exc)[:350]}")
    # If every HF Space fails, preserve the existing Agnes fallback.
    try:
        HF_VIDEO_TASKS[task_id].update({
            "status": "processing", "detail": "Hugging Face Spaces unavailable; starting Agnes fallback..."
        })
        data = await agnes_request("POST", "/v1/videos", payload={
            "model": "agnes-video-2.5-flash", "prompt": prompt, "mode": "text",
            "seconds": "5", "size": "720P", "aspect_ratio": "9:16"
        }, timeout=150)
        video_id = data.get("video_id") or data.get("id")
        if not video_id:
            raise RuntimeError(f"Agnes returned no video task ID: {str(data)[:300]}")
        HF_VIDEO_TASKS[task_id].update({
            "status": "agnes", "agnes_video_id": video_id,
            "agnes_model": "agnes-video-2.5-flash",
            "detail": "Agnes fallback accepted the video task."
        })
    except Exception as exc:
        HF_VIDEO_TASKS[task_id].update({
            "status": "failed",
            "error": "All configured Hugging Face Spaces failed and Agnes fallback could not be started. " +
                     " | ".join(errors[-3:]) + f" | Agnes: {type(exc).__name__}: {str(exc)[:500]}"
        })

def get_api_keys():
    # Keep secrets in Render environment variables; never store them in source code.
    return list(dict.fromkeys(
        value.strip() for value in (
            os.getenv("AGNES_API_KEY", ""),
            os.getenv("AGNES_API_KEY2", ""),
            os.getenv("AGNES_API_KEY3", ""),
        ) if value and value.strip()
    ))

class ImageRequest(BaseModel):
    prompt: str = Field(min_length=1, max_length=2000)
    model: str = "agnes-image-2.1-flash"
    ratio: str = "1:1"
    resolution: str = "1K"
    reference_image: str | None = None

class VideoRequest(BaseModel):
    prompt: str = Field(min_length=1, max_length=2000)
    model: str = "agnes-video-2.5-flash"
    ratio: str = "9:16"
    duration: int = Field(default=5, ge=4, le=12)
    resolution: str = "720P"
    mode: str = "single"
    reference_image: str | None = None

class ChatRequest(BaseModel):
    model: str = "agnes-2.5-flash"
    messages: list[dict] = Field(min_length=1, max_length=80)

def validate_ratio(ratio: str):
    allowed = {"1:1", "16:9", "9:16", "4:3", "3:4", "21:9"}
    if ratio not in allowed:
        raise HTTPException(status_code=400, detail="Unsupported aspect ratio.")
    return ratio

async def agnes_request(method: str, path: str, payload=None, params=None, timeout=120):
    keys = get_api_keys()
    if not keys:
        raise HTTPException(status_code=503, detail="Render environment mein AGNES_API_KEY, AGNES_API_KEY2 ya AGNES_API_KEY3 set nahi hai.")
    last_status = 502
    last_detail = "Agnes API request failed."
    async with httpx.AsyncClient(timeout=timeout) as client:
        for index, key in enumerate(keys):
            try:
                response = await client.request(
                    method,
                    f"{AGNES_BASE_URL}{path}",
                    headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"},
                    json=payload,
                    params=params,
                )
                if response.is_success:
                    try:
                        return response.json()
                    except ValueError:
                        raise HTTPException(status_code=502, detail="Agnes ne invalid JSON response diya.")
                last_status = response.status_code
                last_detail = response.text[:1200] or f"HTTP {response.status_code}"
                # Try the next configured key only for auth, quota, rate-limit, or transient failures.
                if response.status_code not in RETRYABLE or index == len(keys) - 1:
                    break
            except httpx.HTTPError as exc:
                last_status, last_detail = 502, str(exc)
                if index == len(keys) - 1:
                    break
    raise HTTPException(status_code=last_status, detail=f"Agnes API error ({last_status}): {last_detail}")

